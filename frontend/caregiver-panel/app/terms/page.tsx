const CONFIRMATION_TEXT =
  "تمامی مفاد «شرایط و تعهدات عضویت مراقبان در پلتفرم مراقب من» را مطالعه کرده‌ام، با آن موافقم و تأیید می‌کنم که این اقدام به همراه ثبت‌نام نهایی، در حکم امضای الکترونیکی معتبر اینجانب است."

export default function TermsPage() {
  const { user, loading: authLoading } = useAuth(["caregiver"])
  const router = useRouter()

  const [existing, setExisting] = useState<MyWorkPreferences | null>(null)
  const [loading, setLoading] = useState(true)
  const [checked, setChecked] = useState(false)
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState("")

  useEffect(() => {
    if (!user) return
    workPreferencesService.me()
      .then((data) => {
        setExisting(data)
        if (data?.terms_accepted) setChecked(true)
      })
      .finally(() => setLoading(false))
  }, [user])

  if (authLoading || !user) return null

  const alreadyAccepted = existing?.terms_accepted === true

  async function handleConfirm() {
    setSaving(true); setError("")
    try {
      await workPreferencesService.acceptTerms(existing)
      router.push(ROUTES.dashboard)
    } catch (err: any) {
      setError(err?.response?.data?.detail || "ثبت تأیید با خطا مواجه شد.")
    } finally {
      setSaving(false)
    }
  }

  return (
    <div className="min-h-screen bg-gradient-to-b from-pink-50/50 via-background to-background pb-10">
      <header className="sticky top-0 z-10 border-b bg-background/90 backdrop-blur">
        <div className="mx-auto flex max-w-2xl items-center justify-between p-4">
          <h1 className="font-bold text-rose-900">شرایط و تعهدات عضویت</h1>
          <Button variant="ghost" size="sm" onClick={() => router.push(ROUTES.dashboard)}>بازگشت</Button>
        </div>
      </header>

      <main className="mx-auto max-w-2xl space-y-4 p-4">
        {alreadyAccepted && (
          <div className="rounded-lg border border-emerald-200 bg-emerald-50 p-3 text-sm text-emerald-800">
            شما قبلاً این شرایط را پذیرفته‌اید
            {existing?.terms_accepted_at ? ` (${existing.terms_accepted_at})` : ""}.
          </div>
        )}

        {loading ? (
          <Skeleton className="h-96 w-full rounded-2xl" />
        ) : (
          <>
            <Card className="border-pink-100">
              <CardHeader>
                <CardTitle className="text-base text-rose-900">
                  شرایط و تعهدات عضویت و همکاری مراقبان در پلتفرم «مراقب من»
                </CardTitle>
              </CardHeader>
              <CardContent>
                <div className="max-h-[28rem] space-y-4 overflow-y-auto rounded-lg border border-pink-100 bg-pink-50/30 p-4 text-sm leading-relaxed">
                  <p className="text-muted-foreground">
                    اینجانب با ثبت‌نام و ایجاد حساب کاربری در پلتفرم «مراقب من»، ضمن مطالعه کامل این سند،
                    تمامی شرایط و تعهدات مندرج در آن را آگاهانه و با اراده آزاد می‌پذیرم.
                  </p>
                  {SECTIONS.map((section) => (
                    <div key={section.title}>
                      <p className="mb-1 font-semibold text-rose-900">{section.title}</p>
                      <p className="text-muted-foreground">{section.body}</p>
                    </div>
                  ))}
                </div>
              </CardContent>
            </Card>

            <Card className="border-pink-100">
              <CardContent className="space-y-3 p-4">
                {error && <div className="rounded-md bg-rose-50 p-2 text-xs text-rose-700">{error}</div>}
                <label className="flex cursor-pointer items-start gap-2 text-sm">
                  <Checkbox
                    checked={checked}
                    disabled={alreadyAccepted}
                    onChange={(e) => setChecked(e.target.checked)}
                    className="mt-0.5"
                  />
                  <span>{CONFIRMATION_TEXT}</span>
                </label>
                <Button
                  className="w-full"
                  disabled={!checked || saving || alreadyAccepted}
                  onClick={handleConfirm}
                >
                  {saving ? "در حال ثبت..." : alreadyAccepted ? "قبلاً تأیید شده" : "تأیید و ادامه"}
                </Button>
              </CardContent>
            </Card>
          </>
        )}
      </main>
    </div>
  )
}
